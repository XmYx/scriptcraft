//! `cargo xtask strings`: every English source text the interface translates, as
//! `i18n/source-strings.tsv` (context TAB source), ready to start `locales/<locale>/scriptcraft.tsv`
//! in craft-i18n. `--check` fails when the file is stale (CI). `--shared <craft-i18n checkout>`
//! prints which of them craft-i18n's shared `common.tsv` already translates.

use std::collections::BTreeSet;
use std::path::Path;

use scriptcraft_engine::Command;
use scriptcraft_layout::Paper;
use scriptcraft_model::{ElementKind, TitlePage};

const FILE: &str = "i18n/source-strings.tsv";

/// (context, source) rows.
fn rows(root: &Path) -> Result<BTreeSet<(String, String)>, String> {
    let mut rows = BTreeSet::new();
    fn plain(rows: &mut BTreeSet<(String, String)>, s: &str) {
        rows.insert((String::new(), s.to_owned()));
    }
    for k in ElementKind::ALL {
        plain(&mut rows, k.label());
    }
    for p in Paper::ALL {
        plain(&mut rows, p.label());
    }
    for k in TitlePage::STANDARD_KEYS {
        plain(&mut rows, k);
    }
    let src = root.join("crates/ui-egui/src");
    let mut files: Vec<_> = std::fs::read_dir(&src).map_err(|e| format!("{}: {e}", src.display()))?.flatten().map(|e| e.path()).collect();
    files.sort();
    for file in files.iter().filter(|f| f.extension().is_some_and(|e| e == "rs")) {
        let text = std::fs::read_to_string(file).map_err(|e| format!("{}: {e}", file.display()))?;
        for call in ["tr(\"", "trf(\""] {
            for s in literals_after(&text, call) {
                plain(&mut rows, &s);
            }
        }
        // `trn(lang, n, "one", "other")`: an @plural row "one|other".
        let mut rest = text.as_str();
        while let Some(i) = rest.find(".trn(") {
            rest = rest.get(i + 5..).unwrap_or("");
            let quoted = quoted_strings(rest.split(");").next().unwrap_or(""));
            if let [one, other] = quoted.as_slice() {
                rows.insert(("@plural".to_owned(), format!("{one}|{other}")));
            }
        }
        // The keyboard table: `("key", "what")` rows inside `const KEYS`.
        if let Some(start) = text.find("const KEYS") {
            let table = text.get(start..).and_then(|t| t.split("];").next()).unwrap_or("");
            for line in table.lines().filter(|l| l.trim_start().starts_with("(\"")) {
                for s in quoted_strings(line) {
                    rows.insert((String::new(), s));
                }
            }
        }
    }
    for c in Command::all() {
        rows.insert(("@id".to_owned(), c.id()));
        rows.insert((String::new(), c.label().to_owned()));
    }
    Ok(rows)
}

/// String literals right after each occurrence of `call` (which ends with the opening quote).
fn literals_after(text: &str, call: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut rest = text;
    while let Some(i) = rest.find(call) {
        rest = rest.get(i + call.len() - 1..).unwrap_or("");
        if let Some(s) = quoted_strings(rest).into_iter().next() {
            out.push(s);
        }
        rest = rest.get(1..).unwrap_or("");
    }
    out
}

/// Every `"…"` literal in `text`, unescaped for `\"` and `\\`.
fn quoted_strings(text: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut chars = text.chars();
    while let Some(c) = chars.next() {
        if c != '"' {
            continue;
        }
        let mut s = String::new();
        while let Some(c) = chars.next() {
            match c {
                '\\' => {
                    if let Some(n) = chars.next() {
                        s.push(n);
                    }
                }
                '"' => break,
                c => s.push(c),
            }
        }
        out.push(s);
    }
    out
}

fn render(rows: &BTreeSet<(String, String)>) -> String {
    let mut out = String::from(
        "# ScriptCraft interface source texts (generated by `cargo xtask strings`; do not edit).\n\
         # Columns: context <TAB> English source text. A translator copies a row into\n\
         # craft-i18n's locales/<locale>/scriptcraft.tsv and adds the translation as a third column;\n\
         # rows craft-i18n's common.tsv already translates need no copy (`cargo xtask strings --shared`).\n",
    );
    for (context, source) in rows {
        let escaped = source.replace('\\', "\\\\").replace('\t', "\\t").replace('\n', "\\n");
        out.push_str(&format!("{context}\t{escaped}\n"));
    }
    out
}

pub fn run(root: &Path, args: &[String]) -> Result<(), String> {
    let rows = rows(root)?;
    let text = render(&rows);
    let path = root.join(FILE);
    match args.first().map(String::as_str) {
        Some("--check") => {
            let have = std::fs::read_to_string(&path).unwrap_or_default();
            if have == text {
                println!("strings: ok ({} rows)", rows.len());
                Ok(())
            } else {
                Err(format!("{FILE} is stale; run `cargo xtask strings`"))
            }
        }
        Some("--shared") => {
            let dir = args.get(1).ok_or("--shared needs a craft-i18n checkout")?;
            let common = std::fs::read_to_string(Path::new(dir).join("locales/de/common.tsv")).map_err(|e| e.to_string())?;
            let shared: BTreeSet<(String, String)> = common
                .lines()
                .filter(|l| !l.starts_with('#'))
                .filter_map(|l| {
                    let mut cols = l.split('\t');
                    Some((cols.next()?.to_owned(), cols.next()?.to_owned()))
                })
                .collect();
            let hits: Vec<&(String, String)> = rows.iter().filter(|r| shared.contains(*r)).collect();
            println!("{} of {} source texts are in craft-i18n's shared catalog (checked against de/common.tsv):", hits.len(), rows.len());
            for (context, source) in hits {
                println!("{context}\t{source}");
            }
            Ok(())
        }
        _ => {
            if let Some(dir) = path.parent() {
                std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
            }
            std::fs::write(&path, text).map_err(|e| e.to_string())?;
            println!("wrote {FILE} ({} rows)", rows.len());
            Ok(())
        }
    }
}
